//! Session key management for HMAC sealing.
//!
//! Closes OPEN POINT 1 of the specification document: the key k is
//! never used "bare" at the session level. Each session derives its
//! own key via HKDF from a master key, using the session_id
//! (non-secret) as salt. This means compromising one session's key
//! doesn't compromise the others, without paying the latency cost of
//! a Diffie-Hellman exchange per session.
//!
//! Rotation: the master key has a `key_id`. On rotation, a new master
//! is generated with an incremented key_id; the previous one remains
//! active as a fallback for a short window so in-flight sessions
//! aren't invalidated. There is no silent fallback to an unrecognized
//! key_id: if the verifier doesn't have the corresponding master, it's
//! rejected.

use hkdf::Hkdf;
use rand::RngCore;
use sha2::Sha256;
use std::collections::HashMap;
use std::time::{Duration, Instant};

/// Length of the derived session key, in bytes (256 bits).
pub const SESSION_KEY_LEN: usize = 32;

/// Length of the session_id (HKDF salt), in bytes. Not secret.
pub const SESSION_ID_LEN: usize = 16;

/// Fixed domain context for HKDF's "info". Separates this use from any
/// other eventual derivation from the same master (avoids purpose
/// collision, see RFC 5869 §3.2).
const HKDF_INFO: &[u8] = b"lacre-core/v1/session-key";

/// Wire v2 labels. One per purpose, so the key that authenticates a seal can
/// never be the key that drives the state chain, and neither equals a v1 key.
const LABEL_V2_SEAL_KEY: &[u8] = b"lacre/v2/seal-key";
const LABEL_V2_CHAIN_KEY: &[u8] = b"lacre/v2/chain-key";
/// Length of the chain key in bytes (HMAC-SHA256 chain, normative in v2).
pub const V2_CHAIN_KEY_LEN: usize = 32;

/// Master key identifier. Travels in the header alongside the seal so
/// the verifier knows which master to use without having to try them
/// all.
pub type KeyId = u8;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SessionId(pub [u8; SESSION_ID_LEN]);

impl SessionId {
    pub fn generate() -> Self {
        let mut buf = [0u8; SESSION_ID_LEN];
        rand::thread_rng().fill_bytes(&mut buf);
        SessionId(buf)
    }
}

/// An already-derived session key, ready to use in HMAC. Deliberately
/// doesn't implement Debug/Display: it must never end up in a log.
#[derive(Clone)]
pub struct SessionKey {
    pub key_id: KeyId,
    bytes: [u8; SESSION_KEY_LEN],
}

impl Drop for SessionKey {
    fn drop(&mut self) {
        zeroize::Zeroize::zeroize(&mut self.bytes);
    }
}

impl zeroize::ZeroizeOnDrop for SessionKey {}

impl SessionKey {
    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes
    }
}

/// A master key with its identifier and the moment it was registered.
/// Kept by `MasterKeyRing`; never exposed directly outside the ring.
struct MasterKeyEntry {
    key_id: KeyId,
    ikm: Vec<u8>,
    registered_at: Instant,
}

impl Drop for MasterKeyEntry {
    fn drop(&mut self) {
        zeroize::Zeroize::zeroize(&mut self.ikm);
    }
}

/// Holds the active master key and, during the rotation window, the
/// previous one as a fallback. It's the only structure that sees raw
/// master key material.
pub struct MasterKeyRing {
    active: MasterKeyEntry,
    /// Retired keys still valid for verifying in-flight sessions.
    retiring: HashMap<KeyId, MasterKeyEntry>,
    /// How long a retired key remains valid before being purged.
    retirement_window: Duration,
}

impl MasterKeyRing {
    /// Creates a ring with a single active master key (initial use,
    /// H1). `ikm` must come from a high-entropy source
    /// (config.toml with CSPRNG-generated bytes, or a secret store).
    /// The ring doesn't validate entropy; that's the responsibility of
    /// whoever generates the value.
    pub fn new(key_id: KeyId, ikm: Vec<u8>, retirement_window: Duration) -> Self {
        MasterKeyRing {
            active: MasterKeyEntry {
                key_id,
                ikm,
                registered_at: Instant::now(),
            },
            retiring: HashMap::new(),
            retirement_window,
        }
    }

    pub fn active_key_id(&self) -> KeyId {
        self.active.key_id
    }

    /// Rotates to a new master key. The previous one moves to
    /// `retiring` and remains valid for verification (not for new
    /// sealing) during `retirement_window`.
    pub fn rotate(&mut self, new_key_id: KeyId, new_ikm: Vec<u8>) {
        let old = std::mem::replace(
            &mut self.active,
            MasterKeyEntry {
                key_id: new_key_id,
                ikm: new_ikm,
                registered_at: Instant::now(),
            },
        );
        self.retiring.insert(old.key_id, old);
        self.purge_expired();
    }

    fn purge_expired(&mut self) {
        let window = self.retirement_window;
        self.retiring
            .retain(|_, entry| entry.registered_at.elapsed() < window);
    }

    /// Derives the session key for sealing a new fragment. Always uses
    /// the active master.
    pub fn derive_for_sealing(&self, session_id: &SessionId) -> SessionKey {
        derive_session_key(self.active.key_id, &self.active.ikm, session_id)
    }

    /// Derives the session key for verifying a received fragment under
    /// a given key_id. Looks first in the active one, then in
    /// retiring. If the key_id isn't found, returns None: there is no
    /// silent fallback to another key.
    pub fn derive_for_verifying(
        &self,
        key_id: KeyId,
        session_id: &SessionId,
    ) -> Option<SessionKey> {
        if key_id == self.active.key_id {
            return Some(derive_session_key(key_id, &self.active.ikm, session_id));
        }
        self.retiring
            .get(&key_id)
            .map(|entry| derive_session_key(key_id, &entry.ikm, session_id))
    }
}

/// A key derived for one purpose of a wire v2 session. Like `SessionKey` it
/// has no Debug and is wiped on drop.
pub struct ContextKey {
    key_id: KeyId,
    bytes: Vec<u8>,
}

impl ContextKey {
    pub fn key_id(&self) -> KeyId {
        self.key_id
    }
    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes
    }
}

impl Drop for ContextKey {
    fn drop(&mut self) {
        zeroize::Zeroize::zeroize(&mut self.bytes);
    }
}

/// The two keys of a wire v2 session: the seal key (length set by the seal
/// algorithm) and the chain key (always 32 bytes).
pub struct V2Keys {
    pub seal: ContextKey,
    pub chain: ContextKey,
}

impl MasterKeyRing {
    /// Wire v2 keys for sealing, from the active master.
    pub fn derive_v2_for_sealing(
        &self,
        session_id: &SessionId,
        suite_hash: &[u8; 32],
        seal_key_len: usize,
    ) -> Option<V2Keys> {
        derive_v2(self.active.key_id, &self.active.ikm, session_id, suite_hash, seal_key_len)
    }

    /// Wire v2 keys for verifying under `key_id`. Unknown `key_id`: `None`,
    /// never a fallback to another master.
    pub fn derive_v2_for_verifying(
        &self,
        key_id: KeyId,
        session_id: &SessionId,
        suite_hash: &[u8; 32],
        seal_key_len: usize,
    ) -> Option<V2Keys> {
        if key_id == self.active.key_id {
            return derive_v2(key_id, &self.active.ikm, session_id, suite_hash, seal_key_len);
        }
        self.retiring
            .get(&key_id)
            .and_then(|e| derive_v2(key_id, &e.ikm, session_id, suite_hash, seal_key_len))
    }

    /// Whether this ring can derive for `key_id` (active or still retiring).
    pub fn knows_key(&self, key_id: KeyId) -> bool {
        key_id == self.active.key_id || self.retiring.contains_key(&key_id)
    }
}

fn derive_v2(
    key_id: KeyId,
    ikm: &[u8],
    session_id: &SessionId,
    suite_hash: &[u8; 32],
    seal_key_len: usize,
) -> Option<V2Keys> {
    // Same extract step as v1 (session_id as salt); what changes is the
    // expand step: purpose label plus the hash of the whole suite descriptor.
    let hk = Hkdf::<Sha256>::new(Some(&session_id.0), ikm);
    let mut seal = vec![0u8; seal_key_len];
    hk.expand_multi_info(&[LABEL_V2_SEAL_KEY, suite_hash], &mut seal).ok()?;
    let mut chain = vec![0u8; V2_CHAIN_KEY_LEN];
    hk.expand_multi_info(&[LABEL_V2_CHAIN_KEY, suite_hash], &mut chain).ok()?;
    Some(V2Keys {
        seal: ContextKey { key_id, bytes: seal },
        chain: ContextKey { key_id, bytes: chain },
    })
}

fn derive_session_key(key_id: KeyId, ikm: &[u8], session_id: &SessionId) -> SessionKey {
    // HKDF-Extract uses session_id as salt (non-secret, unique per
    // session). HKDF-Expand ties the result to the fixed HKDF_INFO
    // context.
    let hk = Hkdf::<Sha256>::new(Some(&session_id.0), ikm);
    let mut okm = [0u8; SESSION_KEY_LEN];
    hk.expand(HKDF_INFO, &mut okm)
        .expect("SESSION_KEY_LEN is valid for HKDF-SHA256 (max 8160 bytes)");
    SessionKey {
        key_id,
        bytes: okm,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn same_session_id_same_master_yields_same_key() {
        let ring = MasterKeyRing::new(0, b"test-master-key-minimum-32-bytes-".to_vec(), Duration::from_secs(60));
        let sid = SessionId::generate();
        let k1 = ring.derive_for_sealing(&sid);
        let k2 = ring.derive_for_sealing(&sid);
        assert_eq!(k1.as_bytes(), k2.as_bytes());
    }

    #[test]
    fn different_session_ids_yield_different_keys() {
        let ring = MasterKeyRing::new(0, b"test-master-key-minimum-32-bytes-".to_vec(), Duration::from_secs(60));
        let sid_a = SessionId::generate();
        let sid_b = SessionId::generate();
        let ka = ring.derive_for_sealing(&sid_a);
        let kb = ring.derive_for_sealing(&sid_b);
        assert_ne!(ka.as_bytes(), kb.as_bytes());
    }

    #[test]
    fn rotation_keeps_old_key_verifiable_during_window() {
        let mut ring = MasterKeyRing::new(0, b"master-v0-minimum-32-bytes-aaaaa".to_vec(), Duration::from_secs(60));
        let sid = SessionId::generate();
        let sealed_with_v0 = ring.derive_for_sealing(&sid);

        ring.rotate(1, b"master-v1-minimum-32-bytes-bbbbb".to_vec());

        // The session sealed with key_id=0 must still be verifiable.
        let verified = ring
            .derive_for_verifying(0, &sid)
            .expect("key_id=0 must be within the retiring window");
        assert_eq!(sealed_with_v0.as_bytes(), verified.as_bytes());
    }

    #[test]
    fn rotation_rejects_unknown_key_id() {
        let ring = MasterKeyRing::new(0, b"master-v0-minimum-32-bytes-aaaaa".to_vec(), Duration::from_secs(60));
        let sid = SessionId::generate();
        assert!(ring.derive_for_verifying(99, &sid).is_none());
    }

    #[test]
    fn expired_retiring_key_is_purged() {
        let mut ring = MasterKeyRing::new(0, b"master-v0-minimum-32-bytes-aaaaa".to_vec(), Duration::from_millis(50));
        ring.rotate(1, b"master-v1-minimum-32-bytes-bbbbb".to_vec());
        std::thread::sleep(Duration::from_millis(80));
        ring.rotate(2, b"master-v2-minimum-32-bytes-ccccc".to_vec());
        // key_id=0 should have already expired and been purged in this rotate.
        let sid = SessionId::generate();
        assert!(ring.derive_for_verifying(0, &sid).is_none());
    }
}
